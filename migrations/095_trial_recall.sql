-- Trial recall and BOL photo links (docs/deployments/trial-recall.md;
-- receiving_form.py, trial_recall.py, scripts/receiving_form_sync.py,
-- scripts/trial_recall_drill.py). Apply as the app/table owner, port 5432, in one
-- transaction (ON_ERROR_STOP, BEGIN, SET LOCAL lock_timeout='5s',
-- SET LOCAL statement_timeout='60s', SET LOCAL search_path=public, COMMIT).
-- STAGING FIRST; production only with Michael's approval for that step.
--
-- Additive only, safe to rerun: four NEW tables, their indexes, one append-only
-- trigger each (the 039 guard function), RLS on with zero policies (owner-only,
-- like 058/074/076/094), one marker. No existing table, view, trigger or row is
-- touched, and the new tables hold NO foreign key to any existing table
-- (transaction_id / lot_id / product_id are plain numbers), so neither this
-- file nor the two jobs ever take a lock on a ledger table.
--
-- Until the marker exists both jobs refuse to run, the BOL photo list on a
-- receipt is empty and the owner routes answer 503, so code without this
-- migration fails safe.
--
-- The Google Sheet and the Drive photos are independent evidence. These
-- tables only hold what the jobs READ from them (a copy of the Form row as it
-- was seen, and the Drive file id); no photo is ever copied here.

-- One row per nightly read of the Form sheet, written once at the end.
CREATE TABLE IF NOT EXISTS receiving_form_sync_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL,
    finished_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    job_status text NOT NULL CHECK (job_status IN ('completed', 'failed')),
    job_error text,
    sheet_id text NOT NULL,
    tab text NOT NULL,
    rows_read integer NOT NULL DEFAULT 0 CHECK (rows_read >= 0),
    rows_new integer NOT NULL DEFAULT 0 CHECK (rows_new >= 0),        -- new rows, and rows whose content changed
    links_new integer NOT NULL DEFAULT 0 CHECK (links_new >= 0),
    unmatched_count integer NOT NULL DEFAULT 0 CHECK (unmatched_count >= 0),
    -- summary.unmatched: every Form row with no clear FL receipt, with the reason
    -- (the owner's "Receiving form row with no matching FL receipt" list).
    -- summary.link_ids: the receipt_bol_links rows this read stands behind; a
    -- receipt shows only the links of the latest completed read.
    summary jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(summary) = 'object')
);

-- A Form row exactly as it was read. A row whose content (or position) later
-- changes in the sheet is saved again as a new version; the newest id per
-- row_key is the current one. Nothing here is ever updated.
CREATE TABLE IF NOT EXISTS receiving_form_rows (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sheet_id text NOT NULL,
    tab text NOT NULL,
    row_key text NOT NULL CHECK (btrim(row_key) <> ''),   -- the Form timestamp as shown, plus its occurrence number
    row_number integer NOT NULL CHECK (row_number >= 2),  -- sheet row when read (row 1 is the header)
    content_hash text NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    submitted_at timestamptz,                             -- NULL when the timestamp could not be read
    submitted_date date,                                  -- America/New_York
    submitted_by text,
    lot_text text,                                        -- "What lot# did you use?", as typed
    bol_number text,
    carrier text,
    photo_file_ids text[] NOT NULL DEFAULT '{}',          -- Drive file ids from "PICTURE OF BOL"
    products jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(products) = 'array'),
    raw jsonb NOT NULL CHECK (jsonb_typeof(raw) = 'object'),   -- every cell, by header
    first_seen_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT receiving_form_rows_version_key UNIQUE (sheet_id, tab, row_key, content_hash)
);
CREATE INDEX IF NOT EXISTS receiving_form_rows_key_idx ON receiving_form_rows (sheet_id, tab, row_key, id DESC);

-- The link record on a receipt: this Form row (and this Drive photo) is the
-- receiving evidence for this FL receipt. Written only for a clear match
-- (date + internal lot + product); match_basis says what agreed.
CREATE TABLE IF NOT EXISTS receipt_bol_links (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    form_row_id bigint NOT NULL REFERENCES receiving_form_rows(id),
    transaction_id integer NOT NULL,
    receipt_number text,
    lot_id integer NOT NULL,
    product_id integer NOT NULL,
    drive_file_id text NOT NULL DEFAULT '',               -- '' when the Form row has no photo
    match_basis jsonb NOT NULL CHECK (jsonb_typeof(match_basis) = 'object'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT receipt_bol_links_key UNIQUE (form_row_id, transaction_id, lot_id, drive_file_id)
);
CREATE INDEX IF NOT EXISTS receipt_bol_links_transaction_idx ON receipt_bol_links (transaction_id, id);

-- One row per trial recall run, written once at the end with the email
-- delivery result already known.
CREATE TABLE IF NOT EXISTS trial_recall_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL,
    finished_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    plant_date date NOT NULL,                             -- the day the run happened (America/New_York)
    cutoff_date date NOT NULL,
    -- Did the job itself work? Separate from what the tests found.
    job_status text NOT NULL CHECK (job_status IN ('completed', 'failed')),
    job_error text,
    forward_result text CHECK (forward_result IN ('pass', 'fail', 'unverified', 'no_eligible_lot')),
    backward_result text CHECK (backward_result IN ('pass', 'fail', 'unverified', 'no_eligible_lot')),
    full_recall_possible text CHECK (full_recall_possible IN ('yes', 'no', 'not_tested')),
    flag_count integer NOT NULL DEFAULT 0 CHECK (flag_count >= 0),
    email_status text NOT NULL CHECK (email_status IN ('sent', 'failed', 'disabled', 'not_attempted')),
    email_to text,
    email_sent_at timestamptz,
    email_error text,
    email_provider_id text,
    -- The whole result: what was picked, the three-way comparison, the traces,
    -- the flags and the email as sent.
    result jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(result) = 'object'),
    CONSTRAINT trial_recall_runs_result_matches_job CHECK ((job_status = 'completed') = (full_recall_possible IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS trial_recall_runs_plant_date_idx ON trial_recall_runs (plant_date, id DESC);

-- Append-only: the 039 guard function already exists on every ledger table.
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['receiving_form_sync_runs', 'receiving_form_rows', 'receipt_bol_links',
                             'trial_recall_runs'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid = t::regclass
                       AND tgname = t || '_append_only') THEN
            EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON %I FOR EACH ROW '
                           'EXECUTE FUNCTION ledger_block_append_only_change()', t || '_append_only', t);
        END IF;
        IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid = t::regclass) THEN
            EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        END IF;
    END LOOP;
END $$;

