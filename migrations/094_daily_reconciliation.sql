-- Daily inventory reconciliation (docs/verification/daily-reconciliation-scoping.md;
-- reconciliation.py, scripts/daily_reconciliation.py). Apply as the app/table
-- owner, port 5432, in one transaction (ON_ERROR_STOP, BEGIN,
-- SET LOCAL lock_timeout='5s', SET LOCAL statement_timeout='60s',
-- SET LOCAL search_path=public, COMMIT).
-- STAGING FIRST; production only with Michael's approval for that step.
--
-- Additive only, safe to rerun: three NEW tables, their indexes, one append-only
-- trigger each (the 039 guard function), RLS on with zero policies (owner-only,
-- like 058/074/076), one marker. No existing table, view, trigger or row is
-- touched, and the new tables hold NO foreign key to any existing table
-- (lot_id / product_id / transaction_id are plain numbers), so neither this
-- file nor the nightly job ever takes a lock on a ledger table.
--
-- Until the marker exists the job refuses to run and the three read-only
-- endpoints answer 503 RECONCILIATION_UNAVAILABLE, so code without this
-- migration fails safe.
--
-- Append-only means a run is ONE row written once, at the end of the job, with
-- the email delivery result already known. Snapshot and flag rows are written
-- first in the same transaction, which is why their run reference is deferred.

CREATE TABLE IF NOT EXISTS reconciliation_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL,
    finished_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    plant_date date NOT NULL,                       -- the business day checked (America/New_York)
    previous_run_id bigint REFERENCES reconciliation_runs(id),   -- the run whose snapshot was the opening balance
    window_start timestamptz,
    window_end timestamptz,
    -- Did the job itself work? Separate from what the check found.
    job_status text NOT NULL CHECK (job_status IN ('completed', 'failed')),
    job_error text,
    -- What the check found. NULL only when the job failed.
    result text CHECK (result IN ('all_clear', 'attention')),
    balance_checked boolean NOT NULL DEFAULT false, -- false on the first run: no earlier snapshot to roll forward from
    entries_checked integer NOT NULL DEFAULT 0 CHECK (entries_checked >= 0),
    makes_checked integer NOT NULL DEFAULT 0 CHECK (makes_checked >= 0),
    lots_checked integer NOT NULL DEFAULT 0 CHECK (lots_checked >= 0),
    flag_count integer NOT NULL DEFAULT 0 CHECK (flag_count >= 0),            -- every row in reconciliation_flags
    attention_count integer NOT NULL DEFAULT 0 CHECK (attention_count >= 0),  -- the ones that make result = 'attention'
    email_status text NOT NULL CHECK (email_status IN ('sent', 'failed', 'disabled', 'already_sent', 'not_attempted')),
    email_to text,
    email_sent_at timestamptz,
    email_error text,
    email_provider_id text,
    -- The full result: the recipe quantities each make was checked against
    -- (batch_formulas keeps no history), counts, and the email as sent.
    summary jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(summary) = 'object'),
    CONSTRAINT reconciliation_runs_result_matches_job CHECK ((job_status = 'completed') = (result IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS reconciliation_runs_plant_date_idx ON reconciliation_runs (plant_date, id DESC);

CREATE TABLE IF NOT EXISTS inventory_snapshots (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    taken_at timestamptz NOT NULL,
    plant_date date NOT NULL,
    job_run_id bigint NOT NULL REFERENCES reconciliation_runs(id) DEFERRABLE INITIALLY DEFERRED,
    lot_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity_lb numeric(14,4) NOT NULL,             -- posted, void-aware balance; only non-zero lots are stored
    CONSTRAINT inventory_snapshots_run_lot_key UNIQUE (job_run_id, lot_id)
);

CREATE TABLE IF NOT EXISTS reconciliation_flags (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES reconciliation_runs(id) DEFERRABLE INITIALLY DEFERRED,
    kind text NOT NULL CHECK (btrim(kind) <> ''),
    -- alarm: over tolerance or below zero. review: adjustment with no reason / no
    -- named person. yield: coconut over-pack within 2%. info: voids, late entries.
    severity text NOT NULL CHECK (severity IN ('alarm', 'review', 'yield', 'info')),
    product_id integer,
    lot_id integer,
    transaction_id integer,
    expected_lb numeric(14,4),
    actual_lb numeric(14,4),
    difference_lb numeric(14,4),
    tolerance_lb numeric(14,4),
    detail jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(detail) = 'object'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS reconciliation_flags_run_idx ON reconciliation_flags (run_id, id);

-- Append-only: the 039 guard function already exists on every ledger table.
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['reconciliation_runs', 'inventory_snapshots', 'reconciliation_flags'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid = t::regclass
                       AND tgname = t || '_append_only') THEN
            EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON %I FOR EACH ROW '
                           'EXECUTE FUNCTION ledger_block_append_only_change()', t || '_append_only', t);
        END IF;
        IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid = t::regclass) THEN
            EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        END IF;
    END LOOP;
END $$;

